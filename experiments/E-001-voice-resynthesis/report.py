"""E-001 round 1: summarise data/cache/raw.json and results/timing.json into
results/summary.json and results/summary.md. `uv run python report.py`."""

import json
from pathlib import Path

import numpy as np

HERE = Path(__file__).parent
raw = json.loads((HERE / "data" / "cache" / "raw.json").read_text())
timing = json.loads((HERE / "results" / "timing.json").read_text())
rng = np.random.default_rng(20260925)
MODS = ["id", "c25", "c50", "c100", "s50", "s100"]
METHODS = ["world_harvest", "world_dio", "psola"]
GROSS = 50.0


def wilson(k, n, z=1.96):
    if n == 0:
        return (np.nan, np.nan)
    p = k / n
    d = 1 + z * z / n
    c = (p + z * z / (2 * n)) / d
    h = z * np.sqrt(p * (1 - p) / n + z * z / (4 * n * n)) / d
    return (max(0.0, c - h), min(1.0, c + h))


def boot_p95(per_input, reps=1000):
    """95 % bootstrap interval over inputs for the pooled p95 of |err|."""
    vals = []
    for _ in range(reps):
        pick = rng.integers(0, len(per_input), len(per_input))
        vals.append(np.percentile(np.concatenate([per_input[i] for i in pick]), 95))
    return tuple(np.percentile(vals, [2.5, 97.5]))


summary = {}
for kind in ("synthetic", "vocalset"):
    rows = [r for r in raw["results"] if r["kind"] == kind]
    for m in METHODS:
        for mod in MODS:
            rs = [r["mods"][mod] for r in rows if r["method"] == m]
            names = [r["name"] for r in rows if r["method"] == m]
            errs = [np.abs(np.array(r["err"])) for r in rs]
            e = np.concatenate(errs)
            req = np.concatenate([r["req"] for r in rs])
            ach = np.concatenate([r["ach"] for r in rs])
            fine = np.abs(ach - req) <= GROSS
            gross_inputs = sorted({n for n, x in zip(names, errs) if (x > GROSS).any()})
            s = dict(inputs=len(rs), frames=int(len(e)),
                     kept=float(sum(r["n_y"] for r in rs) / sum(r["n_x"] for r in rs)),
                     median=float(np.median(e)), p95=float(np.percentile(e, 95)),
                     p95_ci=[float(v) for v in boot_p95(errs)],
                     fine_p95=float(np.percentile(e[e <= GROSS], 95)),
                     max=float(e.max()),
                     within3=float((e <= 3).mean()), within10=float((e <= 10).mean()),
                     gross=float((e > GROSS).mean()), gross_ci=wilson(int((e > GROSS).sum()), len(e)),
                     gross_inputs=gross_inputs,
                     env_frame_median=float(np.median([r["mcd"] for r in rs])),
                     env_lt_median=float(np.median([r["lt_mcd"] for r in rs])),
                     env_lt_max=float(np.max([r["lt_mcd"] for r in rs])),
                     dhnr_median=float(np.median([r["dhnr"] for r in rs])),
                     req_rms=float(np.sqrt(np.mean(req ** 2))))
            if mod != "id":
                s["achieved_fraction"] = float((ach[fine] * req[fine]).sum() / (req[fine] ** 2).sum())
            if kind == "synthetic":
                a = np.abs(np.concatenate([r["abs_err"] for r in rs]))
                i = np.abs(np.concatenate([r["ideal_abs_err"] for r in rs]))
                s.update(abs_p95=float(np.percentile(a[a <= GROSS], 95)),
                         ideal_abs_p95=float(np.percentile(i[i <= GROSS], 95)))
            summary[f"{kind}/{m}/{mod}"] = s

sc = raw["identity_scale"]
between = sc["between"]["male"] + sc["between"]["female"]
scale = dict(within_median=float(np.median(sc["within"])), within_max=float(np.max(sc["within"])),
             between_median=float(np.median(between)), between_min=float(np.min(between)),
             between_p5=float(np.percentile(between, 5)), n_within=len(sc["within"]),
             n_between=len(between))
t = {}
for m in METHODS:
    rr = [r for r in timing["rows"] if r["method"] == m]
    tot = [r["analyse_per_s"] + r["synth_per_s"] for r in rr]
    t[m] = dict(n=len(rr), analyse_median=float(np.median([r["analyse_per_s"] for r in rr])),
                synth_median=float(np.median([r["synth_per_s"] for r in rr])),
                total_median=float(np.median(tot)), total_max=float(np.max(tot)))
(HERE / "results" / "summary.json").write_text(json.dumps(
    dict(pitch=summary, identity_scale=scale, timing=t, cpu=timing["cpu"]), indent=1))

L = ["# E-001 round 1 summary", "",
     "Generated by `report.py` from `data/cache/raw.json` (not committed; `run.py` rebuilds it) "
     "and `results/timing.json`.", "",
     "## Pitch: achieved against requested", "",
     "Per frame, on squillo's frame axis (E-002's YIN, lag-centre instant): achieved = "
     "YIN(output) − YIN(input) in cents; error = achieved − requested. *kept*: frames YIN measures "
     "in the output over frames it measures in the input. *fraction*: least-squares achieved/requested "
     "over frames with |error| ≤ 50 cents. p95 interval: 95 % bootstrap over inputs. *gross*: |error| > 50 cents.", ""]
for kind in ("synthetic", "vocalset"):
    L += [f"### {kind}", "",
          "| Method | Request | RMS request (c) | Frames | Kept | Median \\|err\\| | p95 \\|err\\| [95 %] | Max | ≤ 3 c | Gross [95 %] | Fraction |"
          + (" Abs p95 | Ideal abs p95 |" if kind == "synthetic" else ""),
          "| :--- | :--- | ---: | ---: | ---: | ---: | ---: | ---: | ---: | ---: | ---: |"
          + (" ---: | ---: |" if kind == "synthetic" else "")]
    for m in METHODS:
        for mod in MODS:
            s = summary[f"{kind}/{m}/{mod}"]
            row = (f"| {m} | {mod} | {s['req_rms']:.1f} | {s['frames']} | {100 * s['kept']:.1f} % | {s['median']:.2f} | "
                   f"{s['p95']:.2f} [{s['p95_ci'][0]:.2f}, {s['p95_ci'][1]:.2f}] | {s['max']:.0f} | "
                   f"{100 * s['within3']:.1f} % | {100 * s['gross']:.2f} % [{100 * s['gross_ci'][0]:.2f}, {100 * s['gross_ci'][1]:.2f}] | "
                   f"{s.get('achieved_fraction', float('nan')):.3f} |")
            if kind == "synthetic":
                row += f" {s['abs_p95']:.2f} | {s['ideal_abs_p95']:.2f} |"
            L.append(row)
    L.append("")
    L += ["Inputs with any gross frame:", ""]
    for m in METHODS:
        gi = sorted({n for mod in MODS for n in summary[f"{kind}/{m}/{mod}"]["gross_inputs"]})
        L.append(f"- {m}: {', '.join(gi) if gi else 'none'}")
    L.append("")
L += ["## Envelope and noise", "",
      "Envelope distance: CheapTrick envelope in dB at 40 mel-spaced frequencies from 80 Hz to 8 kHz, "
      "gain-normalised RMS difference. Reference: the ideal render (synthetic) or the input (VocalSet). "
      "*Frame*: median over voiced frames, then median over inputs. *Long-term*: distance between mean envelopes. "
      "ΔHNR: Praat cross-correlation harmonicity of output minus reference, mean over voiced frames.", "",
      "| Source | Method | Request | Frame (dB) | Long-term (dB) | Long-term max (dB) | ΔHNR (dB) |",
      "| :--- | :--- | :--- | ---: | ---: | ---: | ---: |"]
for kind in ("synthetic", "vocalset"):
    for m in METHODS:
        for mod in MODS:
            s = summary[f"{kind}/{m}/{mod}"]
            L.append(f"| {kind} | {m} | {mod} | {s['env_frame_median']:.2f} | {s['env_lt_median']:.2f} | "
                     f"{s['env_lt_max']:.2f} | {s['dhnr_median']:+.2f} |")
L += ["", "**Identity scale** (VocalSet inputs, unmodified, long-term envelope distance): "
      f"within one singer, first half of the scale against the second: median {scale['within_median']:.2f} dB, "
      f"max {scale['within_max']:.2f} dB ({scale['n_within']} singers). Between singers of the same sex: "
      f"median {scale['between_median']:.2f} dB, 5th percentile {scale['between_p5']:.2f}, min {scale['between_min']:.2f} "
      f"({scale['n_between']} pairs).", "",
      "## Time per second of audio", "",
      f"One process, host CPU ({timing['cpu']}), native code, best of three; inputs: "
      + ", ".join(sorted({r['input'] for r in timing['rows']})) + ".", "",
      "| Method | Analysis (s/s) | Re-synthesis (s/s) | Total median (s/s) | Total max (s/s) |",
      "| :--- | ---: | ---: | ---: | ---: |"]
for m in METHODS:
    x = t[m]
    L.append(f"| {m} | {x['analyse_median']:.3f} | {x['synth_median']:.3f} | {x['total_median']:.3f} | {x['total_max']:.3f} |")
(HERE / "results" / "summary.md").write_text("\n".join(L) + "\n")
print("\n".join(L))
