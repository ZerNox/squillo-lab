"""E-002 round 3, part B: a reverberation estimate from the take itself
(squillo F-030), checked on modelled rooms held out. Crude experiment code.
Needs data/cache/r2/*.npz (r2_truth.py), data/cache/r2_frames.npz
(r2_run.py) and results/fold2.json.

    uv run python r3_room.py run       # writes data/cache/r3_room.pkl (about 2 minutes on 16 processes)
    uv run python r3_room.py sweep     # writes data/cache/r3_sweep.pkl (about 1 minute)
    uv run python r3_room.py analyse   # writes results/r3_room.json

Conditions, written down before generating (S15), each asserted on what
was generated:

- Fitting rooms: nine, RT60 0.3, 0.6 and 1.0 s at direct-to-reverberant
  ratio +12, +6 and 0 dB; round 2's room model (r2_run.rir: a direct
  impulse plus an exponentially decaying Gaussian tail from 2.5 ms), its
  seeding by take and condition name, DRR asserted within 0.1 dB and
  Schroeder T20 within 5 % of RT60, T20 measured on the tail alone. A first
  run measured T20 on the whole response as round 2 did and stopped on its
  own assertion: at +12 dB the direct impulse holds 94 % of the energy, so
  the -5 to -25 dB span straddles the direct step (0.315 s for a 0.3 s
  tail). The tail is what decays at RT60; round 2's two rooms passed either
  way and are regenerated unchanged.
- Held-out rooms: round 2's two, RT60 0.4 s at +6 dB and 0.8 s at 0 dB
  (r2_run.ROOMS), regenerated by r2_run.condition and asserted to give
  round 2's cached pitches frame for frame. Neither RT60 nor either pair is
  in the fitting grid.
- Dry conditions, where a mark is a false mark: the clean re-synthesis,
  white noise at 30, 20 and 10 dB and pink noise at 20 and 10 dB (round 2's
  generator), and the original VocalSet takes (real recordings; their room
  is unknown, and VocalSet's paper describes a treated recording room, so a
  mark there is reported, not scored).
- The tracker as squillo specifies it: base-0.1 (r3_octave.py), acceptance
  E2..C6 widened by 3 cents, the per-frame u of metrics MT-003 (the table
  in results/fold2.json, `measures.spec.table`). Valid frames, truth and
  error as round 2 (r2_run.frame_truth; in a room the truth is the direct
  sound's).

What breaks: the share of accepted frames whose error lies within +-2u
(round 2's coverage). A take is *shown honestly* in a condition when that
coverage over the takes left unmarked is at least 95 %, the coverage k = 2
stands for (GUM, JCGM 100:2008, 6.3.3), and round 2's fold F1 measured
95.2 % clean on held-out singers.

The estimate, from the take's samples alone. L(i) is the level (dB) of
frame i's 1536-sample pitch window; the floor is L's 10th percentile. For
every frame i at least 20 dB above the floor, the fall over the next n
frames, L(i) - L(i + n). In a room, sound decays after the voice stops at
no more than 60 dB per RT60 once the direct sound has gone (Schroeder
1965; Ratnam et al. 2003, doi:10.1121/1.1616578, estimate RT60 blindly from
such free decays), so the steepest fall the take shows bounds the room.
Candidates, fixed before looking at the held-out singers: the largest fall
over n = 6, 12 and 25 frames (48, 96, 200 ms), absolute (dB) or relative to
the level above the floor. Which candidate, and its threshold, are chosen
on the odd singers in the fitting rooms and dry conditions; everything is
then reported on the even singers, in the held-out rooms, and both ways.
The choice, written before running: the candidate and threshold that mark
the fewest dry takes of the fitting fold (clean and noise) while every
fitting room's unmarked takes keep a coverage of at least 95 %.

Added after the first look at the fitting fold, which showed every
decay candidate marking most dry takes (README, round 3): a second family,
the contour's roughness, since reverberation mixes earlier pitches into
the window. Per frame with a pitch and a finite u, and both neighbours
too (no truth used), |p(i) - (p(i-1) + p(i+1)) / 2| in cents; the take's
median and 90th percentile; marked when above the threshold. A 5.5 Hz,
50-cent vibrato alone gives at most 50 (2 pi 5.5 0.008)^2 / 2 = 1.9 cents.
Same choice rule.

The direct sound needed (`sweep`): RT60 0.3, 0.6 and 1.0 s at DRR +18 and
+24 dB, same model and checks, on all singers: the smallest DRR of +12, +18
and +24 dB at which every RT60 keeps a coverage of at least 95 % on each
fold. A condition the singer could be told, not an estimate.
"""
import json
import pickle
import sys
from multiprocessing import Pool

import numpy as np

import r2_run as R
import r2_truth as T
import r3_octave as O
import yin

GRID = {f"room-{rt}+{drr}": (rt, float(drr)) for rt in (0.3, 0.6, 1.0) for drr in (12, 6, 0)}
HELD = ["room-0.4", "room-0.8"]
DRY = ["clean", "white-30", "white-20", "white-10", "pink-20", "pink-10"]
CONDS = DRY + ["original"] + list(GRID) + HELD
NS = (6, 12, 25)
LOUD = 20.0  # dB above the floor for a fall to count
PKL = T.CACHE / "r3_room.pkl"


def condition(y, voiced, name, cond):
    if cond in GRID:
        rt, drr = GRID[cond]
        h, info = rir_tail(rt, drr, R.rng_for(name, cond))
        from scipy.signal import fftconvolve
        return fftconvolve(y, h)[: len(y)], info
    return R.condition(y, voiced, name, cond)


def rir_tail(rt60, drr_db, rng):
    """r2_run.rir's response, drawn the same way; T20 asserted on the tail's own Schroeder decay."""
    n = int(1.5 * rt60 * R.SR)
    t = np.arange(n) / R.SR
    tail = rng.standard_normal(n) * np.exp(-6.908 * t / rt60)
    tail[t < 0.0025] = 0
    tail *= np.sqrt(1.0 / np.sum(tail ** 2) / 10 ** (drr_db / 10))
    h = tail.copy(); h[0] = 1.0
    drr = 10 * np.log10(h[0] ** 2 / np.sum(h[1:] ** 2))
    e = h[1:] ** 2
    edc = 10 * np.log10(np.cumsum(e[::-1])[::-1] / e.sum())
    i5, i25 = np.argmax(edc <= -5), np.argmax(edc <= -25)
    t60 = -60 / np.polyfit(t[1:][i5:i25], edc[i5:i25], 1)[0]
    assert abs(drr - drr_db) <= 0.1 and abs(t60 - rt60) <= 0.05 * rt60, (rt60, drr_db, t60, drr)
    return h, dict(rt60_measured=float(t60), drr_measured=float(drr))


def levels(sig):
    _, win = yin.frame_windows(sig)
    return 10 * np.log10(np.mean(win ** 2, axis=1) + 1e-12)


def falls(L):
    floor = np.percentile(L, 10)
    out = {}
    for n in NS:
        i = np.arange(len(L) - n)
        loud = L[i] - floor >= LOUD
        if not loud.any():
            out[f"abs{n}"] = out[f"rel{n}"] = np.nan
            continue
        d = L[i + n] - L[i]
        d = -d[loud]
        out[f"abs{n}"] = float(d.max())
        out[f"rel{n}"] = float((d / (L[i][loud] - floor)).max())
    out["floor"] = float(floor)
    out["span"] = float(np.percentile(L, 95) - floor)
    return out


def second_diff(f, u):
    """Per frame, |p(i) - (p(i-1) + p(i+1)) / 2| in cents over frames that, with both neighbours,
    have a pitch and a finite u (no truth used); nan elsewhere."""
    p = 1200 * np.log2(np.where(np.isfinite(u), f, np.nan) / 440.0)
    r = np.full(len(p), np.nan)
    r[1:-1] = np.abs(p[1:-1] - (p[:-2] + p[2:]) / 2)
    return r


def roughness(f, u):
    r = second_diff(f, u)
    r = r[np.isfinite(r)]
    if len(r) < 50:
        return dict(rough50=np.nan, rough90=np.nan, rough_n=int(len(r)))
    return dict(rough50=float(np.median(r)), rough90=float(np.percentile(r, 90)), rough_n=int(len(r)))


def one(path):
    z = np.load(T.R2 / (path.stem + ".npz"))
    x, y = z["x"].astype(np.float64), z["y"].astype(np.float64)
    ft = T.truth_per_sample(z["f0"], len(x))
    voiced = ft > 0
    table = O.spec_table()
    res = {}
    for cond in CONDS:
        sig, info = condition(x if cond == "original" else y, voiced, path.stem, cond)
        idx, f, dip = yin.yin(sig)
        f = yin.in_range(f, 3.0)
        f_true, _, valid = R.frame_truth(ft, idx, f)
        ok = valid & ~np.isnan(f)
        e = np.full(len(f), np.nan); e[ok] = 1200 * np.log2(f[ok] / f_true[ok])
        u = O.u_of(dip, table)
        acc = ok & np.isfinite(u)
        L = levels(sig)
        feat = falls(L)
        feat.update(roughness(f, u))
        res[cond] = dict(f=f, e=e, u=u, acc=acc, valid=valid, L=L, feat=feat, info=info)
    return path.stem, res


def run():
    import r2_analyse as A
    res = Pool(16).map(one, T.files())
    # held-out rooms reproduce round 2's cached pitches
    for c in HELD + ["clean", "white-20"]:
        new = np.concatenate([r[1][c]["f"] for r in res])
        old = A.Z[c + "/f"]
        assert np.array_equal(np.isnan(new), np.isnan(old)) and np.allclose(new[~np.isnan(new)], old[~np.isnan(old)], atol=1e-9), c
    rt = {c: [r[1][c]["info"]["rt60_measured"] for r in res] for c in list(GRID) + HELD}
    print("RT60 measured", {c: (round(min(v), 3), round(max(v), 3)) for c, v in rt.items()})
    slim = res
    PKL.write_bytes(pickle.dumps(dict(res=slim, fold=A.FOLD.tolist(), sets=A.SET.tolist())))


SWEEP = {f"room-{rt}+{drr}": (rt, float(drr)) for rt in (0.3, 0.6, 1.0) for drr in (18, 24)}
SPKL = T.CACHE / "r3_sweep.pkl"


def one_sweep(path):
    z = np.load(T.R2 / (path.stem + ".npz"))
    y = z["y"].astype(np.float64)
    ft = T.truth_per_sample(z["f0"], len(y))
    table = O.spec_table()
    out = {}
    from scipy.signal import fftconvolve
    for cond, (rt, drr) in SWEEP.items():
        h, info = rir_tail(rt, drr, R.rng_for(path.stem, cond))
        sig = fftconvolve(y, h)[: len(y)]
        idx, f, dip = yin.yin(sig)
        f = yin.in_range(f, 3.0)
        f_true, _, valid = R.frame_truth(ft, idx, f)
        ok = valid & ~np.isnan(f)
        e = np.full(len(f), np.nan); e[ok] = 1200 * np.log2(f[ok] / f_true[ok])
        u = O.u_of(dip, table)
        out[cond] = dict(e=e, u=u, acc=ok & np.isfinite(u), valid=valid, info=info)
    return path.stem, out


def sweep():
    SPKL.write_bytes(pickle.dumps(Pool(16).map(one_sweep, T.files())))


def cov(rows, ks, c, keep=None):
    a = n = 0
    for k in ks:
        r = rows[k][1][c]
        if keep is not None and not keep(r):
            continue
        m = r["acc"]
        a += int(np.sum(np.abs(r["e"][m]) <= 2 * r["u"][m])); n += int(m.sum())
    return (a / n if n else None), n


FEATS = {"abs6": -1, "abs12": -1, "abs25": -1, "rel12": -1, "rel25": -1, "rough50": 1, "rough90": 1}  # -1: marked below


def marked(r, f, th):
    v = r["feat"][f]
    if not np.isfinite(v):
        return True
    return v < th if FEATS[f] < 0 else v > th


def choose(res, ks, f, bar=0.95):
    vals = sorted(set(float(res[k][1][c]["feat"][f]) for k in ks for c in CONDS if np.isfinite(res[k][1][c]["feat"][f])))
    order = vals if FEATS[f] < 0 else vals[::-1]  # from marking least to marking most
    for th in order:
        worst = min(cov(res, ks, c, lambda r: not marked(r, f, th))[0] or 1.0 for c in GRID)
        if worst >= bar:
            return th
    return None


def report(res, ks, f, th):
    out = {}
    for c in CONDS:
        m = [marked(res[k][1][c], f, th) for k in ks]
        cv, n = cov(res, ks, c, lambda r: not marked(r, f, th))
        out[c] = dict(marked_share=float(np.mean(m)), unmarked_coverage_k2=cv, unmarked_accepted_frames=n)
    return out


def analyse():
    D = pickle.loads(PKL.read_bytes())
    res, fold = D["res"], np.array(D["fold"])
    folds = {1: [k for k in range(len(res)) if fold[k] == 1], 0: [k for k in range(len(res)) if fold[k] == 0]}
    allk = folds[1] + folds[0]
    out = {"coverage_all_takes": {}, "fit": {}, "sweep": {}}
    for c in CONDS:
        out["coverage_all_takes"][c] = {name: dict(zip(("coverage_k2", "accepted_frames"), cov(res, ks, c)))
                                        for name, ks in (("odd", folds[1]), ("even", folds[0]), ("all", allk))}
        out["coverage_all_takes"][c]["features_median_all"] = {f: float(np.nanmedian([res[k][1][c]["feat"][f] for k in allk])) for f in FEATS}
    for fit in (1, 0):
        key = f"fit on {'odd' if fit else 'even'}, test on {'even' if fit else 'odd'}"
        out["fit"][key] = {}
        for f in FEATS:
            th = choose(res, folds[fit], f)
            out["fit"][key][f] = dict(threshold=th, fitting=report(res, folds[fit], f, th) if th is not None else None,
                                      held_out=report(res, folds[1 - fit], f, th) if th is not None else None)
        # the rule's choice across candidates: the fewest dry takes of the fitting fold marked
        dry_marks = {f: float(np.mean([r["fitting"][c]["marked_share"] for c in DRY]))
                     for f, r in out["fit"][key].items() if r["fitting"] is not None}
        out["fit"][key]["chosen"] = dict(feature=min(dry_marks, key=dry_marks.get), dry_marked_fitting=dry_marks)
    # post hoc, after the run: the bar at the fitting fold's own clean coverage (93.9 % odd, 95.2 % even),
    # since the written 95 % lies above the odd singers' clean coverage
    out["fit_post_hoc_bar_clean"] = {}
    for fit in (1, 0):
        key = f"fit on {'odd' if fit else 'even'}, test on {'even' if fit else 'odd'}"
        bar = cov(res, folds[fit], "clean")[0]
        out["fit_post_hoc_bar_clean"][key] = {"bar": bar}
        for f in FEATS:
            th = choose(res, folds[fit], f, bar)
            out["fit_post_hoc_bar_clean"][key][f] = dict(threshold=th, held_out=report(res, folds[1 - fit], f, th) if th is not None else None)
    rows = pickle.loads(SPKL.read_bytes())
    for c in SWEEP:
        out["sweep"][c] = {name: dict(zip(("coverage_k2", "accepted_frames"), cov(rows, ks, c)))
                           for name, ks in (("odd", folds[1]), ("even", folds[0]), ("all", allk))}
        rt = [r[1][c]["info"]["rt60_measured"] for r in rows]
        out["sweep"][c]["rt60_measured_range"] = [min(rt), max(rt)]
    for c in GRID:
        out["sweep"][c] = out["coverage_all_takes"][c]
    need = {}
    for drr in (12, 18, 24):
        ok = all((out["sweep"][f"room-{rt}+{drr}"][fn]["coverage_k2"] or 0) >= 0.95 for rt in (0.3, 0.6, 1.0) for fn in ("odd", "even"))
        need[f"+{drr} dB"] = ok
    out["drr_holds"] = need
    T.OUT.joinpath("r3_room.json").write_text(json.dumps(out, indent=1))
    for c, d in out["coverage_all_takes"].items():
        print(f"{c:12s}", {n: (round(v['coverage_k2'], 3) if v['coverage_k2'] else None, v['accepted_frames']) for n, v in d.items() if n != 'features_median_all'})
    for key, d in out["fit"].items():
        print(key)
        print("   chosen:", d["chosen"]["feature"])
        for f, r in d.items():
            if f == "chosen":
                continue
            if r["threshold"] is None:
                print("  ", f, "no threshold meets the rule"); continue
            h = r["held_out"]
            print("  ", f, round(r["threshold"], 3), "held out: dry marked", {c: round(h[c]["marked_share"], 2) for c in DRY},
                  "rooms marked", {c: round(h[c]["marked_share"], 2) for c in list(GRID) + HELD},
                  "worst unmarked cov", round(min(h[c]["unmarked_coverage_k2"] or 1 for c in list(GRID) + HELD), 3))
    for key, d in out["fit_post_hoc_bar_clean"].items():
        print("post hoc", key, "bar", round(d["bar"], 4))
        for f, r in d.items():
            if f == "bar":
                continue
            h = r["held_out"]
            print("  ", f, r["threshold"] and round(r["threshold"], 3), h and ("clean marked", round(h["clean"]["marked_share"], 2), "white-20 marked", round(h["white-20"]["marked_share"], 2),
                  "worst unmarked room cov", round(min(h[c]["unmarked_coverage_k2"] or 1 for c in list(GRID) + HELD), 3)))
    for c in SWEEP:
        print(c, {n: round(out["sweep"][c][n]["coverage_k2"], 3) for n in ("odd", "even", "all")})
    print("DRR at which every RT60 holds 95 % on both folds:", need)


if __name__ == "__main__":
    {"run": run, "sweep": sweep, "analyse": analyse}[sys.argv[1]]()
