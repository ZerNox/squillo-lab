"""Render results/results.json as results/summary.md. `uv run python report.py`."""

import json
from pathlib import Path

R = Path(__file__).parent / "results"
r = json.loads((R / "results.json").read_text())


def f(v, d=2):
    return "—" if v is None else f"{v:.{d}f}"


def ci(c, d=2, scale=1):
    return "—" if c[0] is None else f"[{c[0] * scale:.{d}f}, {c[1] * scale:.{d}f}]"


L = ["# E-002 round 1 — results", "", "Generated by `report.py` from `results.json`.", "",
     "## Conditions", ""]
for k, v in r["conditions"].items():
    L.append(f"- **{k}:** {v}")
L += ["", f"Runtime {r['runtime_s']:.0f} s.", "", "## squillo `signal` fixtures (SG-001 to SG-006)", "",
      "| Fixture | Frames | Measured / of frames 3.. | Max abs error (cents) |", "| :--- | ---: | ---: | ---: |"]
for k, v in r["fixtures"].items():
    L.append(f"| {k} | {v['frames']} | {v['measured']} / {v['of']} | {f(v.get('max_abs_cents'), 4)} |")

L += ["", "## Accuracy by condition", "",
      "Errors in cents against the true f0 (log-mean over the pitch window unless the row says otherwise). "
      "*Gross*: |error| > 50 cents, as a share of measured frames. *Fine* statistics exclude gross frames. "
      "Brackets: 95 % intervals (Wilson for shares; bootstrap over tones for p95).", "",
      "| Condition | Tracker · reference | Tones | Measured | Gross | Fine median | Fine p95 [95 %] | Fine max | ≤ 3 c of measured [95 %] | Mean signed |",
      "| :--- | :--- | ---: | ---: | ---: | ---: | ---: | ---: | ---: | ---: |"]
for cond, trs in r["accuracy"].items():
    for tr, s in trs.items():
        L.append(
            f"| {cond} | {tr} | {s['tones']} | {100 * s['measured_frac']:.1f} % | "
            f"{100 * s['gross_frac_of_measured']:.2f} % | {f(s['fine_median_abs'])} | "
            f"{f(s['fine_p95_abs'])} {ci(s['fine_p95_ci95'])} | {f(s['fine_max_abs'])} | "
            f"{f(None if s['within_3c_of_measured'] is None else 100 * s['within_3c_of_measured'], 1)} % "
            f"{ci(s['within_3c_ci95'], 1, 100)} | {f(s['fine_mean_signed'])} |")

L += ["", "### By register (YIN and pYIN, log-mean reference)", "",
      "low: E2 to below A3 (220 Hz); mid: A3 to C5; high: above C5 to C6.", "",
      "| Condition | Tracker | Band | Tones | Gross | Fine p95 | Fine max |", "| :--- | :--- | :--- | ---: | ---: | ---: | ---: |"]
for cond, trs in r["accuracy"].items():
    for tr, s in trs.items():
        if not tr.endswith("|logmean"):
            continue
        for b, bs in s["by_band"].items():
            if bs:
                L.append(f"| {cond} | {tr.split('|')[0]} | {b} | {bs['tones']} | "
                         f"{100 * bs['gross_frac_of_measured']:.2f} % | {f(bs['fine_p95_abs'])} | {f(bs['fine_max_abs'])} |")

L += ["", "## Range edges (F-017)", "",
      "Pure tones, 8 trials of 122 frames each. *Outside* > 0 is beyond the range. "
      "*Measured at margin m*: the share of frames reported, when a frame is accepted if YIN's f0 lies "
      "within E2 to C6 widened by m cents.", "",
      "| Edge | Cents outside | YIN found a period | YIN max abs error | Measured, m = 0 | m = 3 | m = 6 |",
      "| :--- | ---: | ---: | ---: | ---: | ---: | ---: |"]
for k, v in r["edges"].items():
    m = v["measured_frac_by_accept_margin"]
    L.append(f"| {v['edge']} | {v['cents_outside']:g} | {100 * v['yin_found_frac']:.1f} % | "
             f"{f(v['yin_max_abs_err_cents'], 3)} | {100 * m['0.0']:.1f} % | {100 * m['3.0']:.1f} % | {100 * m['6.0']:.1f} % |")

p = r["precision_f32_vs_f64"]
L += ["", "## float32 vs float64 arithmetic in YIN", "",
      f"{p['frames']} frames (pure and −12 dB/oct tones on the 41 semitones E2 to C6): "
      f"{p['decision_mismatches']} measured/unmeasurable disagreements; max |Δ| {p['max_abs_cents']:.4f} cents, "
      f"p99 {p['p99_abs_cents']:.4f} cents.", ""]
(R / "summary.md").write_text("\n".join(L))
print("wrote results/summary.md")
